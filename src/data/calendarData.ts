/**
 * Calculates the Yoruba 4-day traditional cycle for any given calendar date.
 * Uses an epoch anchor calibrated to the traditional Yoruba sacred calendar.
 */
export function getTraditionalDayForDate(date: Date = new Date()): TraditionalDay {
  // Base anchor: Jan 1, 2024 was mapped to Day 1 (Ọjọ́ Awo)
  const anchorDate = new Date(2024, 0, 1).getTime();
  const targetDate = new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime();
  const dayDifference = Math.floor((targetDate - anchorDate) / (1000 * 60 * 60 * 24));
  
  // Modulo 4 with positive wrap
  const cycleIndex = ((dayDifference % 4) + 4) % 4;
  return TRADITIONAL_DAYS[cycleIndex];
}

