/**
 * Searches the traditional dream corpus and scores matches against user's dream narrative
 */
export function interpretDreamText(text: string): {
  matchedSymbols: DreamSymbol[];
  summary: string;
  ancestralAdvice: string;
  ritualGuidance: string;
} {
  const lowerText = text.toLowerCase();
  
  const matched = DREAM_SYMBOLS.filter(symbol => {
    return symbol.keywords.some(kw => lowerText.includes(kw));
  });

  if (matched.length === 0) {
    return {
      matchedSymbols: [],
      summary: 'Àyẹ̀wò Àlá (Dream Reflection): Your dream carries subtle energetic movements of your inner consciousness (Orí). In Yorùbá cosmology, every dream without an overt omen is an invitation to listen closely to your emotional state upon awakening.',
      ancestralAdvice: 'When a dream defies simple categorization, observe how your chest and breath felt upon opening your eyes: Was there lightness, anxiety, or heavy anticipation? Your Orí uses dreams to process the invisible currents of your daily path.',
      ritualGuidance: 'Place both hands upon your forehead at morning light. Breathe deeply four times and declare: "Orí mi, kọ́ mi ní ìmọ̀ ìkọ̀kọ̀" (My inner consciousness, teach me hidden knowledge).'
    };
  }

  const primary = matched[0];
  const summary = `Detected ${matched.length} sacred Yorùbá archetype${matched.length > 1 ? 's' : ''}: ${matched.map(m => m.yorubaTitle).join(', ')}. Principal resonance connects to ${primary.orishaConnection}.`;
  
  return {
    matchedSymbols: matched,
    summary,
    ancestralAdvice: primary.ancestralGuidance,
    ritualGuidance: primary.recommendedRitual
  };
}
